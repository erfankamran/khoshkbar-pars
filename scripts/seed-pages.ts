const PAGES = [
  {
    slug: 'terms',
    title: 'قوانین و شرایط استفاده',
    body: TERMS_BODY,
    sortOrder: 0,
    showInFooter: true,
  },
];

let created = 0;
for (const p of PAGES) {
  const exists = await db.contentPage.findUnique({ where: { slug: p.slug }, select: { id: true } });
  if (exists) {
    console.log(`↩︎ page «${p.slug}» exists — skipped`);
    continue;
  }
  await db.contentPage.create({ data: p });
  created++;
  console.log(`✅ created page «${p.slug}» (${p.title})`);
}
console.log(`— ${created} page(s) created`);
await db.$disconnect();
