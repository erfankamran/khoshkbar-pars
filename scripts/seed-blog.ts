let created = 0;
for (const p of POSTS) {
  const exists = await db.post.findUnique({ where: { slug: p.slug }, select: { id: true } });
  if (exists) {
    console.log(`↩︎ post «${p.slug}» exists — skipped`);
    continue;
  }
  await db.post.create({
    data: {
      ...p,
      isPublished: true,
      publishedAt: new Date(),
      metaTitle: p.title,
      metaDescription: p.excerpt,
    },
  });
  created++;
  console.log(`✅ created post «${p.slug}» (${p.title})`);
}
console.log(`— ${created} post(s) created`);
await db.$disconnect();
